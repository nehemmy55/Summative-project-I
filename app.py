"""Streamlit app for the AfriMed QA assistant. Run: streamlit run app.py"""
import streamlit as st

from src.inference import MedicalAssistant

st.set_page_config(page_title="AfriMed QA Assistant", page_icon="🩺", layout="centered")


@st.cache_resource(show_spinner="Loading the fine-tuned model ...")
def get_assistant():
    # load the model once and reuse it
    return MedicalAssistant()


try:
    assistant = get_assistant()
except Exception as error:
    st.error(f"The model could not be loaded: {error}")
    st.stop()

MAX_CHARS = 1500


def ask(question, options=None):
    """Run the pipeline and show a message instead of a traceback if something goes wrong."""
    if len(question) > MAX_CHARS:
        st.warning(f"Only the first {MAX_CHARS} characters of the question are used.")
        question = question[:MAX_CHARS]
    try:
        with st.spinner("Thinking ..."):
            return assistant.answer(question, options)
    except Exception as error:
        st.error(f"Something went wrong while answering: {error}")
        return None

st.title("🩺 AfriMed QA Assistant")
st.caption(
    "A small health question-answering model (FLAN-T5-small, 77M parameters) fine-tuned on "
    "AfriMed-QA, a dataset of medical questions written by clinicians and students in African countries."
)
st.warning(
    "Educational prototype. Answers are generated by a small model and are often wrong or incomplete. "
    "Do not use them for diagnosis or treatment — consult a qualified health worker.",
    icon="⚠️",
)

OPEN_EXAMPLES = [
    "What are the symptoms of malaria?",
    "What is the first-line treatment for uncomplicated malaria in Africa?",
    "How can cholera be prevented?",
    "What causes sickle cell disease?",
    "Who won the Africa Cup of Nations in 2019?",
]
MCQ_EXAMPLE = {
    "question": "Which of the following is the commonest cause of anaemia in pregnancy in sub-Saharan Africa?",
    "options": "Iron deficiency\nVitamin B12 deficiency\nSickle cell disease\nHookworm infestation\nThalassaemia",
}


def show_details(result):
    with st.expander("How this answer was produced"):
        st.write(f"**Domain gate:** probability that this is a health question = `{result['p_health']:.2f}` "
                 f"(answered only if ≥ 0.50).")
        ref = result["reference"]
        if ref:
            used = "given to the model as context" if assistant.use_rag else "shown for reference only"
            st.write(f"**Closest entry in the knowledge base** (TF-IDF cosine similarity "
                     f"`{ref['score']:.2f}`, {used}):")
            st.write(f"*Q:* {ref['kb_question']}")
            st.write(f"*A:* {ref['kb_passage']}")
            if ref["score"] < 0.2:
                st.info("Low similarity: the training data contains nothing close to this question, "
                        "so the answer is less likely to be reliable.")


open_tab, mcq_tab, about_tab = st.tabs(["Ask a question", "Multiple-choice question", "About"])

with open_tab:
    if "open_q" not in st.session_state:
        st.session_state.open_q = ""
    st.write("Try an example:")
    for i, example in enumerate(OPEN_EXAMPLES):
        if st.button(example, key=f"ex{i}"):
            st.session_state.open_q = example
    question = st.text_area("Your health question (English)", key="open_q", height=90)
    if st.button("Get answer", type="primary", key="ask_open") and question.strip():
        result = ask(question)
        if result:
            if result["in_domain"]:
                st.success(result["answer"] or "(the model produced an empty answer)")
            else:
                st.error(result["answer"])
            show_details(result)

with mcq_tab:
    st.write("Paste an exam-style question and its options (one per line). "
             "The model generates an answer and the closest option is selected.")
    if st.button("Load an example", key="mcq_ex"):
        st.session_state.mcq_q = MCQ_EXAMPLE["question"]
        st.session_state.mcq_o = MCQ_EXAMPLE["options"]
    mcq_question = st.text_area("Question", key="mcq_q", height=90)
    mcq_options = st.text_area("Options (one per line)", key="mcq_o", height=140)
    if st.button("Answer", type="primary", key="ask_mcq") and mcq_question.strip():
        options = [line for line in mcq_options.splitlines() if line.strip()]
        if len(options) < 2:
            st.error("Please enter at least two options.")
        else:
            with st.spinner("Thinking ..."):
                result = assistant.answer(mcq_question, options)
            st.write(f"**Model output:** {result['answer']}")
            if result["picked_option"]:
                st.success(f"Selected option: {result['picked_option']}")
            else:
                st.info("The model output did not clearly match any option.")
            show_details(result)

with about_tab:
    st.markdown(
        """
**Pipeline**

1. **Domain gate** – a TF-IDF + logistic-regression classifier trained on health questions
   (AfriMed-QA) and general questions (WebQuestions, TREC) decides whether the question is about health.
   Other questions are refused.
2. **Retriever** – TF-IDF search over the training questions and answers finds the closest known entry.
3. **Generator** – FLAN-T5-small, fine-tuned on AfriMed-QA (and MedQuAD), writes the answer.

**Known limitations**

- With five options, the model is right on only a minority of exam questions — a 77M-parameter model
  cannot store much medical knowledge.
- Answers can be fluent but wrong (hallucination). Always check the reference entry.
- English only; no Kinyarwanda, Swahili or other African languages.
        """
    )
